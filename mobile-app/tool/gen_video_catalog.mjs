// tool/gen_video_catalog.mjs
//
// Builds lib/data/video_catalog.dart from the website's video list so the two
// never drift apart by hand-copying.
//
//   Source of truth: frontend/app/data/videos.data.ts
//   Usage (from the mobile-app folder):
//     node tool/gen_video_catalog.mjs ../frontend/app/data/videos.data.ts
//
// Needs only Node. It reads the .ts file as text, finds every object literal
// that has an `_id: '...'` property, and evaluates just those literals.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const input = process.argv[2];
if (!input) {
  console.error('Usage: node tool/gen_video_catalog.mjs <path to videos.data.ts>');
  process.exit(1);
}

const source = readFileSync(resolve(input), 'utf8');

// ── 1. Find every {...} pair, ignoring braces inside strings and comments ────
function findBracePairs(text) {
  const pairs = [];
  const stack = [];
  let i = 0;
  while (i < text.length) {
    const ch = text[i];
    const next = text[i + 1];
    if (ch === '/' && next === '/') { // line comment
      while (i < text.length && text[i] !== '\n') i++;
      continue;
    }
    if (ch === '/' && next === '*') { // block comment
      i += 2;
      while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) i++;
      i += 2;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === '`') { // string
      const quote = ch;
      i++;
      while (i < text.length && text[i] !== quote) {
        if (text[i] === '\\') i++;
        i++;
      }
      i++;
      continue;
    }
    if (ch === '{') stack.push(i);
    if (ch === '}') {
      const start = stack.pop();
      if (start !== undefined) pairs.push([start, i]);
    }
    i++;
  }
  return pairs;
}

const pairs = findBracePairs(source);

// ── 2. For each `_id: '...'`, take the innermost object that contains it ─────
const idPattern = /\b_id\s*:\s*['"]/g;
const objects = [];
const seenStarts = new Set();
let match;
while ((match = idPattern.exec(source)) !== null) {
  let best = null;
  for (const [start, end] of pairs) {
    if (start < match.index && end > match.index) {
      if (best === null || start > best[0]) best = [start, end];
    }
  }
  if (best && !seenStarts.has(best[0])) {
    seenStarts.add(best[0]);
    objects.push(source.slice(best[0], best[1] + 1));
  }
}

if (objects.length === 0) {
  console.error('No objects with an _id: \'...\' property were found in ' + input);
  process.exit(1);
}

// ── 3. Evaluate each literal and keep the fields the app needs ───────────────
const KNOWN = new Set(['_id', 'title', 'description', 'filePath', 'category', 'language', 'duration']);
const videos = [];
const unmapped = new Set();
const problems = [];

for (const text of objects) {
  let value;
  try {
    value = new Function('"use strict"; return (' + text + ');')();
  } catch (error) {
    problems.push('Could not read this object: ' + text.slice(0, 90).replace(/\s+/g, ' ') + '... (' + error.message + ')');
    continue;
  }
  for (const key of Object.keys(value)) if (!KNOWN.has(key)) unmapped.add(key);

  const str = (v) => (typeof v === 'string' ? v : '');
  const video = {
    id: str(value._id),
    title: str(value.title),
    description: str(value.description),
    category: str(value.category),
    language: str(value.language),
    filePath: str(value.filePath),
    duration: typeof value.duration === 'string' ? value.duration : '',
  };
  if (!video.id || !video.title || !video.filePath) {
    problems.push('Missing _id, title or filePath: ' + JSON.stringify(value).slice(0, 120));
    continue;
  }
  videos.push(video);
}

const ids = videos.map((v) => v.id);
const duplicates = ids.filter((id, i) => ids.indexOf(id) !== i);
if (duplicates.length) problems.push('Duplicate ids: ' + [...new Set(duplicates)].join(', '));

if (problems.length) {
  console.error('Problems found, nothing was written:\n - ' + problems.join('\n - '));
  process.exit(1);
}

// ── 4. Write the Dart file ───────────────────────────────────────────────────
function dartString(s) {
  return "'" + String(s)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\$/g, '\\$')
    .replace(/\r/g, '\\r')
    .replace(/\n/g, '\\n') + "'";
}

const entries = videos.map((v) => {
  const lines = [
    `    id: ${dartString(v.id)},`,
    `    title: ${dartString(v.title)},`,
    `    description: ${dartString(v.description)},`,
    `    category: ${dartString(v.category)},`,
    `    language: ${dartString(v.language)},`,
    `    filePath: ${dartString(v.filePath)},`,
  ];
  if (v.duration) lines.push(`    duration: ${dartString(v.duration)},`);
  return `  CatalogVideo(\n${lines.join('\n')}\n  ),`;
});

const dart = `// lib/data/video_catalog.dart
//
// GENERATED by tool/gen_video_catalog.mjs. Do not edit by hand.
// Source of truth: frontend/app/data/videos.data.ts
// After the website's video list changes, run from the mobile-app folder:
//   node tool/gen_video_catalog.mjs ../frontend/app/data/videos.data.ts
//
// \`id\` is the same static id the website sends to /api/videos/:id/watch and the
// one the backend stores in UserVideo.videoId (for example 'en-1').

class CatalogVideo {
  const CatalogVideo({
    required this.id,
    required this.title,
    required this.description,
    required this.category,
    required this.language,
    required this.filePath,
    this.duration,
  });

  final String id;
  final String title;
  final String description;
  final String category;
  final String language;

  /// Path on the website host, for example '/videos/v1/phising attack.mp4'.
  final String filePath;
  final String? duration;

  /// Display name of the language. The website stores codes ('en', 'ur').
  String get languageLabel {
    switch (language) {
      case 'en':
        return 'English';
      case 'ur':
        return 'Urdu';
    }
    if (language.isNotEmpty) return language;
    return id.startsWith('ur-') ? 'Urdu' : 'English';
  }
}

const List<CatalogVideo> kVideoCatalog = [
${entries.join('\n')}
];
`;

const out = resolve('lib/data/video_catalog.dart');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, dart, 'utf8');

const languages = [...new Set(videos.map((v) => v.languageLabel ?? v.language))];
console.log(`Wrote ${videos.length} videos to lib/data/video_catalog.dart`);
console.log('Languages:  ' + ([...new Set(videos.map((v) => v.language || '(empty)'))].join(', ')));
console.log('Categories: ' + ([...new Set(videos.map((v) => v.category || '(empty)'))].join(', ')));
if (unmapped.size) console.log('Ignored fields: ' + [...unmapped].join(', '));
